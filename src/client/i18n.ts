/** 取一个翻译函数：优先 locale 服务，其次本地 zh 字典。 */
export function createTranslator(ctx: ClientCtx, onLocaleChange?: () => void): (key: string, vars?: Record<string, string | number>) => string {
  try {
    ctx.locale.register(NS, { zh, en });
  } catch (error) {
    console.warn('[square] locale.register failed', error);
  }
  if (onLocaleChange !== undefined) {
    try {
      ctx.locale.subscribe?.(onLocaleChange);
    } catch {
      /* 订阅失败不影响渲染 */
    }
  }
  const local = (key: string, vars?: Record<string, string | number>): string =>
    format(zh[key] ?? key, vars);
  try {
    const bound = ctx.locale.bind(NS);
    return (key, vars) => {
      try {
        const value = bound(key, vars);
        return value === key ? local(key, vars) : value;
      } catch {
        return local(key, vars);
      }
    };
  } catch {
    return local;
  }
}

/** `{name}` 插值。 */
export function format(template: string, vars?: Record<string, string | number>): string {
  if (vars === undefined) return template;
  return template.replace(/\{(\w+)\}/g, (match, key: string) =>
    Object.prototype.hasOwnProperty.call(vars, key) ? String(vars[key]) : match,
  );
}
